#!/usr/bin/env python3
"""Generate sig.h for the ASI plugin from the stock WHGame.dll and the proven cave.bin.
usage: gen_sig.py STOCK_WHGAME_DLL CAVE_BIN TAIL_OFFSET_HEX OUT_H"""
import sys, re, hashlib
dll, cave_path, tail_hex, out = sys.argv[1:5]
d = open(dll, 'rb').read()
assert hashlib.sha256(d).hexdigest() == 'cf9f6dc384edcf35c20647a912745ddb8adb5ba65953e329c24e89dd9c4381aa', 'not the stock WHGame.dll of Steam 1.9.8 (build 22623230)'
BASE, TEXT_RVA, TEXT_RAW, TEXT_VSIZE = 0x180000000, 0x1000, 0x400, 0x218473a
off = lambda va: va - BASE - TEXT_RVA + TEXT_RAW
PRE_A, HOOK, RET, POST_B = 0x180522ecd, 0x180522f96, 0x180522fa0, 0x180522fc2
pre = d[off(PRE_A):off(HOOK)]
hook = d[off(HOOK):off(RET)]
post = d[off(RET):off(POST_B)]
assert hook.hex() == '4883c218f3410f59348f'
# the only rip-relative operand in the prefix: mulss xmm7,[rip+disp32] at 0x180522ee4 (f3 0f 59 3d + disp32)
w = 0x180522ee8 - PRE_A
assert pre[w-4:w] == bytes.fromhex('f30f593d')
mask = bytearray(b'\x01' * len(pre)); mask[w:w+4] = b'\x00' * 4
assert pre[:7] == bytes.fromhex('488b8530020000')          # mov rax,[rbp+0x230]
text = d[TEXT_RAW:TEXT_RAW + TEXT_VSIZE]
rx = re.compile(b''.join(re.escape(pre[i:i+1]) if mask[i] else b'.' for i in range(len(pre))), re.S)
hits = [m.start() for m in rx.finditer(text)]
assert hits == [PRE_A - BASE - TEXT_RVA], hits
cave = open(cave_path, 'rb').read(); tail = int(tail_hex, 16)
assert cave[tail] == 0xE9 and cave[tail+1:tail+5] == b'\0\0\0\0' and cave[:7] == pre[:7]
arr = lambda b: ','.join('0x%02x' % x for x in b)
open(out, 'w').write(
    '/* generated by gen_sig.py: do not edit */\n'
    '#define SIG_PRE_LEN %d\n#define SIG_POST_LEN %d\n#define HOOK_LEN %d\n#define CAVE_LEN %d\n#define CAVE_TAIL_OFF %d\n'
    '#define STOCK_HOOK_RVA 0x%x\n'
    'static const unsigned char SIG_PRE[SIG_PRE_LEN] = {%s};\n'
    'static const unsigned char SIG_PRE_MASK[SIG_PRE_LEN] = {%s};\n'
    'static const unsigned char HOOK_ORIG[HOOK_LEN] = {%s};\n'
    'static const unsigned char SIG_POST[SIG_POST_LEN] = {%s};\n'
    'static const unsigned char CAVE[CAVE_LEN] = {%s};\n'
    % (len(pre), len(post), len(hook), len(cave), tail, HOOK - BASE, arr(pre), arr(mask), arr(hook), arr(post), arr(cave)))
print('sig.h: prefix %d bytes (4 wildcards), hook %d, suffix %d, cave %d; prefix unique in stock .text' % (len(pre), len(hook), len(post), len(cave)))
