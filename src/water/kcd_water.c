/* KCDWater - water ripple smoothing plugin (ASI) for Kingdom Come: Deliverance (KCD1), part of the 30 FPS Grass & Water Fix.
 *
 * The game steps its water ripple simulation (CWaterRipples::Render) every 25 ms, at most once per frame, and the water
 * shaders read the same ripple texture ($WaterRipplesDDN_0) until the next step: ripples look like ~30 fps at any frame
 * rate. Mode 1 (patch B, FINDINGS_WATER_RIPPLES.md section 3) keeps the 25 ms simulation untouched and shows, on every
 * frame, lerp(previous step, current step, alpha) with the game's own precompiled BlurInterpolation technique:
 *   - before a step the true state is put back into the DDN, so the simulation input is the stock one;
 *   - after a step the new true state is saved (C), the old one becomes the previous state (P);
 *   - every frame DDN = lerp(P, C, alpha), alpha = time since the step / 25 ms; then the DDN mips are rebuilt.
 *   v1: on a step that re-centred the simulation (camera snap) the previous state is dropped for that step (counted).
 *
 * Modes (KCDWater.ini at start, KCDWater.cmd at any time; the .cmd file is deleted after it ran):
 *   mode 0   stock: the hook only counts
 *   mode 1   patch B blend (default since 1.0.0-rc1)
 *   mode 2   test patch A1: the game's gate takes its multi-GPU branch and steps every frame (jne -> jmp, one byte;
 *            restored when the mode is left). Changes the ripple speed: test only.
 *   stats    counters to KCDWater.log (calls, frames, steps, step intervals, gate check, blends, snaps, alpha, ...)
 *   reset    zero the counters
 *   verify   mode 1: compare the DDN with the saved state once at the next restore and once at the next save (GPU
 *            read-back of mip 0; debug only, stalls one frame)
 *
 * Rules: every engine address comes from byte signatures (sig.h, generated by gen_sig.py from the stock DLL), each must
 * match exactly once and every decoded value is cross-checked against the helper bodies; any failure = nothing is
 * changed in the game. No C runtime, kernel32 only (d3d11.h is used for types and COM vtable macros only).
 *
 * Calling conventions: every engine function called here was checked at its existing call site(s) in WHGame.dll
 * (Steam 1.9.8 VAs given at each typedef). gen_sig/clobber scan: no call site of any of these helpers reads rcx, rdx,
 * r8-r11 or xmm1-xmm5 after the call before writing them, except one game caller of ShEndPass (0x18206a254) that
 * keeps r10 across it (LTCG knowledge; irrelevant for us, we treat all volatile registers as clobbered, MS x64 ABI).
 */
