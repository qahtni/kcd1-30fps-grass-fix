    volatile ULONGLONG calls, gun_hits, gun_full, mcalls[3], frames, maxcalls, steps, will_nostep, step_nowill, blends, restores, saves, snaps,
        stepped_dirty, same_frame, nop_alpha1, verify_busy, fs[FS_N], ahist[10];
